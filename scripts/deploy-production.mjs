/**
 * One command production deploy of Zolva to Cloudflare Workers.
 *
 *   npm run deploy:prod
 *
 * 1. Builds the app with OpenNext and deploys the "pitwise" Worker
 *    (https://zolvaagent.app; pitwise.hoodguard.workers.dev stays on as a fallback).
 * 2. Sets the Worker secrets: Supabase URL and key, the chain RPC URL (and Privy, if set) from
 *    .dev.vars, plus a
 *    production cron secret and session secret. Those two are generated once
 *    and kept in .prod.vars (gitignored), so redeploys do not log users out.
 * 3. Points the Supabase pg_cron backup at the Worker (secret goes straight
 *    into Supabase Vault).
 * 4. Checks /api/health on the live site.
 *
 * Secrets are never printed.
 */
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "node:child_process";

import { createClient } from "@supabase/supabase-js";

const SITE = "https://zolvaagent.app";
const root = new URL("..", import.meta.url);

function readVars(file) {
  const path = new URL(file, root);
  if (!existsSync(path)) return {};
  return Object.fromEntries(
    readFileSync(path, "utf8")
      .split(/\r?\n/)
      .filter((line) => /^[A-Z_]+=/.test(line))
      .map((line) => [line.slice(0, line.indexOf("=")), line.slice(line.indexOf("=") + 1).trim()]),
  );
}

function run(command, args) {
  console.log(`\n> ${command} ${args.join(" ")}`);
  const result = spawnSync(command, args, { cwd: root, stdio: "inherit", shell: process.platform === "win32" });
  if (result.status !== 0) throw new Error(`${command} ${args.join(" ")} failed`);
}

async function main() {
  const dev = readVars(".dev.vars");
  if (!dev.SUPABASE_URL || !dev.SUPABASE_SERVICE_ROLE_KEY) throw new Error("SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY must be set in .dev.vars");
  if (!dev.ROBINHOOD_RPC_URL) throw new Error("ROBINHOOD_RPC_URL must be set in .dev.vars (hourly prices are read from chain)");

  // Production-only secrets, created on the first deploy and reused after.
  const prod = readVars(".prod.vars");
  if (!prod.CRON_SECRET || !prod.SESSION_SECRET) {
    prod.CRON_SECRET = randomBytes(32).toString("hex");
    prod.SESSION_SECRET = randomBytes(32).toString("hex");
    writeFileSync(
      new URL(".prod.vars", root),
      `# Production secrets for the Cloudflare Worker (generated by deploy:prod). Never commit.\nCRON_SECRET=${prod.CRON_SECRET}\nSESSION_SECRET=${prod.SESSION_SECRET}\n`,
    );
    console.log("Generated production secrets in .prod.vars");
  }

  console.log(dev.PRIVY_APP_ID && dev.PRIVY_APP_SECRET ? "Privy: email and Google login on" : "Privy: not set in .dev.vars, wallet login only");
  console.log(dev.OPENROUTER_API_KEY ? "AI co-pilot: on" : "AI co-pilot: no OPENROUTER_API_KEY in .dev.vars, off");
  run("npx", ["opennextjs-cloudflare", "build"]);
  run("npx", ["opennextjs-cloudflare", "deploy"]);

  const secretsFile = join(tmpdir(), `zolva-secrets-${Date.now()}.json`);
  writeFileSync(
    secretsFile,
    JSON.stringify({
      SUPABASE_URL: dev.SUPABASE_URL,
      SUPABASE_SERVICE_ROLE_KEY: dev.SUPABASE_SERVICE_ROLE_KEY,
      ROBINHOOD_RPC_URL: dev.ROBINHOOD_RPC_URL,
      CRON_SECRET: prod.CRON_SECRET,
      SESSION_SECRET: prod.SESSION_SECRET,
      // Optional: without these the live site offers wallet login only.
      ...(dev.PRIVY_APP_ID && dev.PRIVY_APP_SECRET ? { PRIVY_APP_ID: dev.PRIVY_APP_ID, PRIVY_APP_SECRET: dev.PRIVY_APP_SECRET } : {}),
      // Optional: without a key the AI co-pilot stays off and agents trade on their rules.
      ...(dev.OPENROUTER_API_KEY ? { OPENROUTER_API_KEY: dev.OPENROUTER_API_KEY } : {}),
      ...(dev.AI_DAILY_BUDGET_USD ? { AI_DAILY_BUDGET_USD: dev.AI_DAILY_BUDGET_USD } : {}),
    }),
  );
  try {
    run("npx", ["wrangler", "secret", "bulk", secretsFile]);
  } finally {
    rmSync(secretsFile, { force: true });
  }

  const db = createClient(dev.SUPABASE_URL, dev.SUPABASE_SERVICE_ROLE_KEY, { auth: { persistSession: false } });
  const { error } = await db.rpc("configure_hourly_tick", { p_url: `${SITE}/api/cron/tick`, p_secret: prod.CRON_SECRET });
  if (error) throw new Error(`Scheduling the pg_cron backup failed: ${error.message}`);
  console.log("\npg_cron backup scheduled (minute 7 of every hour).");

  // Secrets take a few seconds to reach the Worker.
  for (let attempt = 1; attempt <= 6; attempt++) {
    await new Promise((resolve) => setTimeout(resolve, 5000));
    const response = await fetch(`${SITE}/api/health`).catch(() => null);
    const body = response ? await response.text() : "no response";
    console.log(`health check ${attempt}: ${response?.status ?? "-"} ${body}`);
    if (response?.ok) {
      console.log(`\nLive: ${SITE}`);
      return;
    }
  }
  throw new Error("The site did not report healthy. Check the Worker logs in the Cloudflare dashboard.");
}

main().catch((cause) => {
  console.error(`\nDeploy failed: ${cause instanceof Error ? cause.message : cause}`);
  process.exit(1);
});
